        ["users", "role", "role_enum", "NOT NULL, default Reader", "Enum: Reader, Librarian, Administrator."],
        ["users", "is_active", "BOOLEAN", "NOT NULL, default true", "Account activation flag (false blocks login)."],
        ["users", "created_at", "TIMESTAMPTZ(3)", "NOT NULL, default now()", "Account registration timestamp."],
        ["users", "updated_at", "TIMESTAMPTZ(3)", "NOT NULL, updated at", "Timestamp of last profile update."],
        # book_titles
        ["book_titles", "id", "UUID", "PRIMARY KEY, default uuid()", "Unique identifier for catalog title."],
        ["book_titles", "isbn", "VARCHAR(20)", "NOT NULL, UNIQUE", "Unique ISBN identifier (10 or 13 digits)."],
        ["book_titles", "title", "VARCHAR(255)", "NOT NULL", "Title of publication."],
