        ["loans", "returned_at", "TIMESTAMPTZ(3)", "NULL", "Check-in instant; NULL denotes active loan."],
        ["loans", "renewed_at", "TIMESTAMPTZ(3)", "NULL", "Renewal instant under BR-03."],
        # reservations
        ["reservations", "id", "UUID", "PRIMARY KEY, default uuid()", "Unique reservation record identifier."],
        ["reservations", "reader_id", "UUID", "NOT NULL, FK -> users(id)", "Patron placing hold (onDelete: Restrict)."],
