        "The schema models 5 primary relational tables: users, book_titles, book_copies, loans, and reservations. "
        "All primary keys are UUID v4 values generated by the database engine to guarantee global uniqueness. "
        "All foreign keys enforce ON DELETE RESTRICT constraints to satisfy BR-09 (preventing deletion of titles or copies with circulation history). "
        "Circulation timestamps are stored in timestamptz(3) with UTC normalization."
