        # loans
        ["loans", "id", "UUID", "PRIMARY KEY, default uuid()", "Unique circulation loan transaction identifier."],
        ["loans", "reader_id", "UUID", "NOT NULL, FK -> users(id)", "Borrowing reader (onDelete: Restrict)."],
        ["loans", "copy_id", "UUID", "NOT NULL, FK -> book_copies(id)", "Borrowed copy (onDelete: Restrict)."],
        ["loans", "checked_out_at", "TIMESTAMPTZ(3)", "NOT NULL, default now()", "Checkout instant."],
